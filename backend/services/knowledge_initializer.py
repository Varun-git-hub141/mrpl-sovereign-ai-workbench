def initialize_knowledge_base():
    """Initializes the on-premise knowledge repository files on disk."""
    base_dir = KNOWLEDGE_ROOT / "engineering_formulas"
    
    categories = [
        "corrosion", "pressure", "flow", "pumps", "vessels", "heat_transfer",
        "thermodynamics", "mechanical", "electrical", "instrumentation", "process",
        "units", "reliability", "inspection", "maintenance", "financial", "spreadsheet", "date_calculations"
    ]
    
    for cat in categories:
        (base_dir / cat).mkdir(parents=True, exist_ok=True)
        
    created_formulas = 0
    for item in FORMULAS_DATA:
        folder = base_dir / item["category_folder"]
        formula_id = item["data"]["formula_id"]
        filepath = folder / f"{formula_id}.json"
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(item["data"], f, indent=2)
        created_formulas += 1

    # Initialize P&ID components
    created_components = 0
    for comp in PND_COMPONENTS:
        comp_dir = KNOWLEDGE_ROOT / comp["folder"]
        comp_dir.mkdir(parents=True, exist_ok=True)
        filepath = comp_dir / comp["filename"]
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(comp["data"], f, indent=2)
        created_components += 1

    print(f"[OK] Initialized Knowledge Base with {created_formulas} formula definitions across {len(categories)} categories.")
    print(f"[OK] Initialized {created_components} P&ID component knowledge files in knowledge/.")


if __name__ == "__main__":
    initialize_knowledge_base()
